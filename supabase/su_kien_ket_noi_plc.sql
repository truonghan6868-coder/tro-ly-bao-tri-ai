-- Bảng lưu sự kiện mất kết nối / phục hồi PLC
-- Nguồn ghi: plc_logger.py (ghi_su_kien_ket_noi)
-- Nguồn đọc: modules/tab_giam_sat.py (khối "Lịch sử kết nối PLC")
--
-- Cách dùng: mở Supabase Dashboard > SQL Editor > dán toàn bộ file này > Run.

create table if not exists public.su_kien_ket_noi_plc (
    id bigint generated by default as identity primary key,
    thoi_gian text,
    su_kien text not null,               -- MAT_KET_NOI | KHOI_PHUC
    chi_tiet text,
    thoi_gian_gian_doan_giay double precision,
    vi_tri_may text
);

create index if not exists idx_su_kien_ket_noi_plc_thoi_gian
    on public.su_kien_ket_noi_plc (thoi_gian desc);

-- Bật RLS + policy tối thiểu cho anon key đang dùng trong plc_logger.py / Streamlit.
-- Nếu dự án đã có policy riêng, có thể bỏ qua phần này.
alter table public.su_kien_ket_noi_plc enable row level security;

drop policy if exists "su_kien_ket_noi_plc_doc" on public.su_kien_ket_noi_plc;
create policy "su_kien_ket_noi_plc_doc"
    on public.su_kien_ket_noi_plc
    for select
    using (true);

drop policy if exists "su_kien_ket_noi_plc_ghi" on public.su_kien_ket_noi_plc;
create policy "su_kien_ket_noi_plc_ghi"
    on public.su_kien_ket_noi_plc
    for insert
    with check (true);
